"""Bundle every runtime module and mission source into one deployable DCS Hook."""
from pathlib import Path
import hashlib
import json

ROOT = Path(__file__).resolve().parents[1]
DESTINATION = ROOT / "dist" / "DcsEsport"
HOOK_RELATIVE = "Scripts/Hooks/DcsEsportHook.lua"
MODULES = {
    "json": "src/shared/json.lua",
    "collector": "src/mission/collector.lua",
    "bridge": "src/hook/bridge.lua",
    "recorder": "src/hook/recorder.lua",
    "transport": "src/hook/transport.lua",
    "players": "src/hook/players.lua",
}
LEGACY_OUTPUTS = (
    "Scripts/DcsEsport/shared/json.lua",
    "Scripts/DcsEsport/mission/collector.lua",
    "Scripts/DcsEsport/hook/bridge.lua",
    "Scripts/DcsEsport/hook/recorder.lua",
    "Scripts/DcsEsport/config.example.lua",
)


def lua_long_string(text: str) -> str:
    """Choose a delimiter absent from source; Lua consumes the added first newline."""
    equals = ""
    while f"]{equals}]" in text or text.endswith(f"]{equals}"):
        equals += "="
    return f"[{equals}[\n{text}]{equals}]"


def render() -> str:
    config = (ROOT / "config/hook.example.lua").read_text(encoding="utf-8")
    entry = (ROOT / "src/hook/DcsEsportHook.lua").read_text(encoding="utf-8")
    parts = [
        "-- DCS Esport: self-contained Hook, generated by tools/package.py.\n",
        "-- Copy this ONE file to Saved Games/<DCS profile>/Scripts/Hooks/.\n",
        "-- The mission collector is injected from embedded source; no companion files.\n\n",
        "-- BEGIN CONFIG (editable)\nlocal config = (function()\n",
        config, "\nend)()\n-- END CONFIG\n\nlocal embedded = {\n",
    ]
    for name, source in MODULES.items():
        text = (ROOT / source).read_text(encoding="utf-8")
        parts.append(f"    {name} = {lua_long_string(text)},\n")
    parts.extend(["}\n\nlocal start = (function()\n", entry, "\nend)()\nstart(embedded, config)\n"])
    return "".join(parts)


def build() -> Path:
    target = DESTINATION / HOOK_RELATIVE
    target.parent.mkdir(parents=True, exist_ok=True)
    target.write_text(render(), encoding="utf-8", newline="\n")
    # Remove ONLY named obsolete generated files in our own staging directory.
    # Installed DCS profiles and user configuration are never cleaned here.
    for relative in LEGACY_OUTPUTS:
        obsolete = (DESTINATION / relative).resolve()
        if not obsolete.is_relative_to(DESTINATION.resolve()):
            raise ValueError("Legacy staging path escaped the package directory")
        if obsolete.is_file():
            obsolete.unlink()
        parent = obsolete.parent
        while parent != DESTINATION and parent.is_relative_to(DESTINATION.resolve()):
            try:
                parent.rmdir()  # Only empty directories, never recursive removal.
            except OSError:
                break
            parent = parent.parent
    manifest = {HOOK_RELATIVE: hashlib.sha256(target.read_bytes()).hexdigest()}
    (DESTINATION / "manifest.json").write_text(
        json.dumps({"version": "0.3.2", "layout": "single_hook", "sha256": manifest}, indent=2) + "\n", encoding="utf-8"
    )
    return DESTINATION


if __name__ == "__main__":
    print(build() / HOOK_RELATIVE)
